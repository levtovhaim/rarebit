#!/usr/bin/env python3
"""Generate hebrew-normalize's Unicode tables and its NFC/NFD test vectors.

Run from the repository root, with the Python from .mise.toml:

    python native/hebrew-normalize/tools/gen_unicode_data.py

It writes src/unicode_tables.inc and tests/data/unicode_vectors.tsv. The output depends only on
Python's Unicode version, so re-running it changes nothing until Python is upgraded. Commit
the script and both outputs together. The data comes from the Unicode Character Database
(Unicode License v3) through Python's unicodedata module.
"""

from __future__ import annotations

import random
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "src" / "unicode_tables.inc"
VECTORS = ROOT / "tests" / "data" / "unicode_vectors.tsv"

HEBREW_SCOPE = [*range(0x0590, 0x0600), *range(0xFB1D, 0xFB50)]
LATIN_FOLD_SCOPE = range(0x00C0, 0x0180)  # Latin-1 Supplement letters and Latin Extended-A
MAX_SEQUENCE = 4  # char32_t sequence[4] in unicode.cpp
RANDOM_VECTORS = 600
SEED = 20261124


def assigned(cp: int) -> bool:
    return unicodedata.category(chr(cp)) != "Cn"


def code_points(s: str) -> list[int]:
    return [ord(c) for c in s]


def hexs(values: list[int]) -> str:
    return " ".join(f"{v:04X}" for v in values)


def decomposition_rows(form: str) -> list[tuple[int, list[int]]]:
    rows = []
    for cp in HEBREW_SCOPE:
        if not assigned(cp):
            continue
        decomposed = unicodedata.normalize(form, chr(cp))
        if decomposed != chr(cp):
            seq = code_points(decomposed)
            if len(seq) > MAX_SEQUENCE:
                sys.exit(f"U+{cp:04X}: {form} has {len(seq)} code points, more than {MAX_SEQUENCE}")
            rows.append((cp, seq))
    return rows


def check_nfc_equals_nfd() -> None:
    """The C++ to_nfc() is to_nfd(): true only while Hebrew never recomposes."""
    for cp in HEBREW_SCOPE:
        if assigned(cp):
            ch = chr(cp)
            if unicodedata.normalize("NFC", ch) != unicodedata.normalize("NFD", ch):
                sys.exit(f"U+{cp:04X}: NFC differs from NFD; to_nfc() needs real composition now")


def combining_rows() -> list[tuple[int, int]]:
    return [
        (cp, unicodedata.combining(chr(cp)))
        for cp in HEBREW_SCOPE
        if assigned(cp) and unicodedata.combining(chr(cp)) != 0
    ]


def latin_fold_rows() -> list[tuple[int, str]]:
    rows = []
    for cp in LATIN_FOLD_SCOPE:
        if not assigned(cp):
            continue
        base = unicodedata.normalize("NFD", chr(cp))[0]
        if base.isascii() and base.isalpha():
            rows.append((cp, base.lower()))
    return rows


def write_tables() -> None:
    canonical = decomposition_rows("NFD")
    compatibility = decomposition_rows("NFKD")
    lines = [
        "// Generated by native/hebrew-normalize/tools/gen_unicode_data.py. Do not edit by hand.",
        f"// Unicode Character Database {unicodedata.unidata_version} (Unicode License v3), through Python's",
        f"// unicodedata module (Python {sys.version_info.major}.{sys.version_info.minor}). Every table is sorted by code point.",
        "",
        f'constexpr char kUnicodeDataVersion[] = "{unicodedata.unidata_version}";',
        "",
        "// Full canonical decompositions (NFD) in the Hebrew scope.",
        "constexpr Decomposition kCanonical[] = {",
    ]
    lines += [f"    {{0x{cp:04X}, {{{', '.join(f'0x{v:04X}' for v in seq)}}}, {len(seq)}}}," for cp, seq in canonical]
    lines += [
        "};",
        "",
        "// Full compatibility decompositions (NFKD) in the Hebrew scope.",
        "constexpr Decomposition kCompatibility[] = {",
    ]
    lines += [
        f"    {{0x{cp:04X}, {{{', '.join(f'0x{v:04X}' for v in seq)}}}, {len(seq)}}}," for cp, seq in compatibility
    ]
    lines += [
        "};",
        "",
        "// Non-zero canonical combining classes in the Hebrew scope.",
        "constexpr CombiningClass kCombiningClasses[] = {",
    ]
    lines += [f"    {{0x{cp:04X}, {ccc}}}," for cp, ccc in combining_rows()]
    lines += [
        "};",
        "",
        "// Latin letters with diacritics, folded to their lowercase ASCII base letter.",
        "constexpr LatinFold kLatinFolds[] = {",
    ]
    lines += [f"    {{0x{cp:04X}, '{ascii_letter}'}}," for cp, ascii_letter in latin_fold_rows()]
    lines += ["};", ""]
    TABLES.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_vectors() -> None:
    rng = random.Random(SEED)
    letters = list(range(0x05D0, 0x05EB))
    marks = [cp for cp in range(0x0591, 0x05C8) if assigned(cp) and unicodedata.category(chr(cp)) == "Mn"]
    presentation = [cp for cp in range(0xFB1D, 0xFB50) if assigned(cp)]
    pool = letters * 4 + marks * 3 + presentation + [0x0020, 0x05BE, 0x05F3, 0x05F4]

    inputs = [[cp] for cp in HEBREW_SCOPE if assigned(cp)]
    for _ in range(RANDOM_VECTORS):
        inputs.append([rng.choice(pool) for _ in range(rng.randint(1, 7))])

    lines = [
        f"# NFC and NFD of Hebrew text, from Python's unicodedata (Unicode {unicodedata.unidata_version}).",
        "# Generated by native/hebrew-normalize/tools/gen_unicode_data.py. Do not edit by hand.",
        "# input<TAB>nfc<TAB>nfd, each a list of hex code points",
    ]
    for seq in inputs:
        s = "".join(chr(cp) for cp in seq)
        nfc = code_points(unicodedata.normalize("NFC", s))
        nfd = code_points(unicodedata.normalize("NFD", s))
        lines.append(f"{hexs(seq)}\t{hexs(nfc)}\t{hexs(nfd)}")
    lines.append("")
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    VECTORS.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> None:
    check_nfc_equals_nfd()
    write_tables()
    write_vectors()
    print(f"Unicode {unicodedata.unidata_version}: wrote {TABLES.relative_to(ROOT)} and {VECTORS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
